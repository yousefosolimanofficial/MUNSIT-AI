#!/usr/bin/env node
/**
 * Imports the official MUNSIT icon library from raw Figma SVG exports (Phase 02 step 5).
 *
 * Usage: node scripts/import-figma-icons.mjs <dir-with-raw-exports>
 *   The directory holds one `<name>.svg` per icon, exported from Figma (`download_assets`, SVG)
 *   for the `Icon / <name>` components listed in src/design-system/icons/manifest.ts.
 *
 * What it does — and nothing more:
 *   1. Takes only the shapes inside `<g id="Icon / <name>">`; drops the Figma frame
 *      backgrounds, wrapper groups and layer ids that the export adds around the icon.
 *   2. Keeps every shape attribute exactly as exported (paths, rect, stroke width, caps, joins).
 *   3. Writes src/design-system/icons/svg/<name>.svg — the original geometry and original
 *      color (#9C9C9D) in a clean 24×24 SVG.
 *   4. Writes src/design-system/icons/geometry.generated.ts — the same shapes with the stroke
 *      color replaced by `currentColor`, as data for the Icon component (no innerHTML).
 *
 * Node built-ins only. Never edit the outputs by hand; re-run this script instead.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const iconsDir = join(root, "src/design-system/icons");
const rawDir = process.argv[2];
if (!rawDir) {
  console.error("Usage: node scripts/import-figma-icons.mjs <dir-with-raw-exports>");
  process.exit(1);
}

// Names come from the manifest so the import cannot drift from the documented list.
const manifestSource = readFileSync(join(iconsDir, "manifest.ts"), "utf8");
const names = [...manifestSource.matchAll(/^\s{2}(\w+): \{ figmaNode:/gm)].map((m) => m[1]);
if (names.length === 0) throw new Error("No icon names found in manifest.ts");

const SHAPE = /<(path|rect|circle|ellipse|line|polyline|polygon)\b([^>]*?)\/?>/g;
const ATTR = /([\w-]+)="([^"]*)"/g;
const ORIGINAL_STROKE = "#9C9C9D";
const toReactProp = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

/** Inner markup of `<g id="Icon / <name>">`, balancing nested <g> tags. */
function iconGroup(svg, name) {
  const open = `<g id="Icon / ${name}">`;
  const start = svg.indexOf(open);
  if (start === -1) throw new Error(`${name}: group "Icon / ${name}" not found`);
  let depth = 1;
  const tag = /<\/?g\b[^>]*>/g;
  tag.lastIndex = start + open.length;
  for (let m = tag.exec(svg); m; m = tag.exec(svg)) {
    depth += m[0].startsWith("</") ? -1 : m[0].endsWith("/>") ? 0 : 1;
    if (depth === 0) return svg.slice(start + open.length, m.index);
  }
  throw new Error(`${name}: unbalanced <g> in export`);
}

const geometry = {};
mkdirSync(join(iconsDir, "svg"), { recursive: true });

for (const name of names) {
  const raw = readFileSync(join(rawDir, `${name}.svg`), "utf8");
  if (!/viewBox="0 0 24 24"/.test(raw)) throw new Error(`${name}: export is not 24×24`);
  const inner = iconGroup(raw, name);
  if (/transform=/.test(inner)) throw new Error(`${name}: unexpected transform inside icon`);

  const shapes = [...inner.matchAll(SHAPE)].map(([, tag, attrs]) => ({
    tag,
    attrs: [...attrs.matchAll(ATTR)].filter(([, k]) => k !== "id").map(([, k, v]) => [k, v]),
  }));
  if (shapes.length === 0) throw new Error(`${name}: no shapes`);
  for (const { attrs } of shapes) {
    for (const [k, v] of attrs) {
      if ((k === "stroke" || k === "fill") && v !== ORIGINAL_STROKE) {
        throw new Error(`${name}: unexpected ${k}="${v}" — only ${ORIGINAL_STROKE} is mapped`);
      }
    }
  }

  const body = shapes
    .map(({ tag, attrs }) => `  <${tag} ${attrs.map(([k, v]) => `${k}="${v}"`).join(" ")}/>`)
    .join("\n");
  writeFileSync(
    join(iconsDir, "svg", `${name}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none">\n${body}\n</svg>\n`,
  );

  geometry[name] = shapes.map(({ tag, attrs }) => [
    tag,
    Object.fromEntries(
      attrs.map(([k, v]) => [toReactProp(k), k === "stroke" || k === "fill" ? "currentColor" : v]),
    ),
  ]);
}

const ts = `/*
 * GENERATED by scripts/import-figma-icons.mjs from the official Figma exports — do not edit.
 * Geometry is identical to ./svg/*.svg; only the stroke color is "currentColor".
 */
import type { IconName } from "./manifest";

export type IconShape = readonly [
  tag: "path" | "rect" | "circle" | "ellipse" | "line" | "polyline" | "polygon",
  props: Readonly<Record<string, string>>,
];

export const ICON_GEOMETRY: Readonly<Record<IconName, readonly IconShape[]>> = ${JSON.stringify(geometry, null, 2)};
`;
writeFileSync(join(iconsDir, "geometry.generated.ts"), ts);
console.log(`Imported ${names.length} icons.`);
